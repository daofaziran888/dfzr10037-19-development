def enrich_lineage_rows(rows: list[dict[str, Any]]) -> None:
    """给仓库里原有的血缘示例补齐双时间字段，保证旧数据也能被版本定界查询。"""
    default_day = "2026-09-01"
    for row in rows:
        record_id = int(row.get("id", 0))
        row.setdefault("链路编号", f"DATA-{record_id:04d}")
        fallback = str(row.get("最后更新") or "")
        try:
            date.fromisoformat(fallback[:10])
        except ValueError:
            fallback = default_day
        row.setdefault("生效时间", fallback)
        row.setdefault("记录时间", row.get("生效时间", fallback))
        row.setdefault("失效时间", "")
        row.setdefault("撤销时间", "")
        row.setdefault("版本", 1)
        row.setdefault("原记录ID", record_id)
        row.setdefault("取代记录ID", "")
        row.setdefault("登记方式", "初始登记")
